class SejongChatbot:
    def __init__(self):
        self.kb = KNOWLEDGE_BASE

    def system_prompt(self) -> str:
        return (
            "============================================================\n"
            "   [세종문화회관 대관 안내 AI 챗봇 시스템 프롬프트 (System Prompt)]\n"
            "============================================================\n"
            "역할: 세종문화회관 대관 서비스 전문 AI 어시스턴트\n"
            "원칙:\n"
            " 1. 세종문화회관 대관규정 및 공연장대관내규에 명시된 사실만 안내합니다.\n"
            " 2. 모든 대관료 및 부대설비 사용료에는 '부가가치세(VAT) 별도' 임을 명시합니다.\n"
            " 3. 기본 사용시간(공연 5시간, 준비 4시간)과 초과 30분 단위 요금을 명확히 고지합니다.\n"
            " 4. 친절하고 정중하며 격식 있는 어조(하십시오/해요 체)를 유지합니다.\n"
            "============================================================\n"
        )

    def calculate_estimate(self, venue: str, genre: str, show_count: int, prep_type: str = "기본4시간", prep_count: int = 1, equipment_list: list = None) -> dict:
        """대관료 계산 엔진"""
        if venue not in self.kb["venues"]:
            return {"error": f"존재하지 않는 공연장입니다: {venue}"}

        v_data = self.kb["venues"][venue]
        
        # 공연 대관료
        show_rate = v_data["공연대관"].get(genre, v_data["공연대관"].get("공연", 0))
        total_show_fee = show_rate * show_count

        # 준비 대관료
        prep_key = f"준비철수_{prep_type}"
        prep_rate = v_data.get(prep_key, {}).get(genre, v_data.get(prep_key, {}).get("공연", 0))
        total_prep_fee = prep_rate * prep_count

        # 부대설비 요금
        equip_detail = []
        total_equip_fee = 0
        if equipment_list:
            for item in equipment_list:
                name = item.get("name")
                qty = item.get("qty", 1)
                days = item.get("days", 1)
                if name in self.kb["equipment"]:
                    unit_fee = self.kb["equipment"][name]["요금"]
                    fee = unit_fee * qty * days
                    total_equip_fee += fee
                    equip_detail.append({
                        "항목": name,
                        "수량": qty,
                        "일수": days,
                        "단가": unit_fee,
                        "소계": fee
                    })
                elif name == "SR확성":
                    sr_fee = v_data.get("SR확성_1일", 0) * days
                    total_equip_fee += sr_fee
                    equip_detail.append({"항목": f"SR확성({venue})", "수량": 1, "일수": days, "단가": v_data.get("SR확성_1일", 0), "소계": sr_fee})

        subtotal = total_show_fee + total_prep_fee + total_equip_fee
        vat = int(subtotal * 0.1)
        grand_total = subtotal + vat

        # 정기/수시 계약금 산출
        reg_deposit = int(subtotal * 0.2)
        ad_deposit = int(subtotal * 0.4)

        return {
            "공연장": venue,
            "장르": genre,
            "공연회수": show_count,
            "공연대관료_소계": total_show_fee,
            "준비대관유형": prep_type,
            "준비대관회수": prep_count,
            "준비대관료_소계": total_prep_fee,
            "부대설비_내역": equip_detail,
            "부대설비_소계": total_equip_fee,
            "공급가액(VAT별도)": subtotal,
            "부가가치세(10%)": vat,
            "합계금액(VAT포함)": grand_total,
            "정기대관_계약금(20%)": reg_deposit,
            "수시대관_계약금(40%)": ad_deposit
        }

