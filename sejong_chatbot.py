# CLI 대화형 루프 실행 기능
def run_cli_chatbot():
    bot = SejongChatbot()
    print(bot.system_prompt())
    print("챗봇이 실행되었습니다. 질문을 입력하세요. (종료하려면 'exit' 또는 'quit' 입력)\n")
    while True:
        try:
            user_in = input("사용자 > ")
            if user_in.strip().lower() in ["exit", "quit"]:
                print("챗봇을 종료합니다.")
                break
            if not user_in.strip():
                continue
            response = bot.answer_query(user_in)
            print(f"\nAI 챗봇 >\n{response}\n")
        except (KeyboardInterrupt, EOFError):
            break

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--cli":
        run_cli_chatbot()
    else:
        bot = SejongChatbot()
        print(bot.system_prompt())
        print("--- 테스트 실행 ---")
